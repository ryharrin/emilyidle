export function getWatchById(watchId: string): Watch | null {
  return WATCH_CATALOG.find((w) => w.id === watchId) ?? null
}

export function getPassiveEnjoymentRate(watch: Watch): number {
  // AC: favorites generate a passive enjoyment bonus.
  const favoriteMultiplier = watch.isFavorite ? 1.25 : 1
  return watch.enjoymentRate * favoriteMultiplier
}

// Helper functions for watch tier operations
export function getWatchesByTier(tier: WatchTier): Watch[] {
  return WATCH_CATALOG.filter((w) => w.tier === tier)
}

export function getFavoriteWatches(): Watch[] {
  return WATCH_CATALOG.filter((w) => w.isFavorite)
}

export function getTotalWatchCount(): number {
  return WATCH_CATALOG.length
}

export function getTierWatchCount(tier: WatchTier): number {
  return getWatchesByTier(tier).length
}
